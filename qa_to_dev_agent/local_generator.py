from __future__ import annotations

from .project_scan import ProjectContext


def generate_local_task(qa_input: str, context: ProjectContext, extra_docs: str | None = None) -> str:
    docs_summary = _summarize_docs(extra_docs)
    return f"""# 开发任务标题

基于测试输入生成开发任务说明

## 背景

测试工程师提供了偏验收视角的需求或问题描述，需要转换为开发工程师或 Codex CLI 可执行的任务说明。

## 测试输入摘要

{qa_input.strip()}

## 当前项目上下文

{context.to_markdown()}

## 已识别的关键代码位置

{_list_or_unknown(context.key_code_locations)}

## 当前调用链理解

当前只进行了静态只读扫描。已识别入口、脚本和候选文件，但调用链仍需开发执行阶段继续确认，不应基于本摘要直接改动业务代码。

## 开发目标

根据测试输入定位真实入口和调用链，完成最小范围实现，并保持现有业务契约不被破坏。

## 实现要求

- 优先验证当前运行平台、入口文件、路由、接口封装和状态管理链路。
- 只修改与需求直接相关的文件。
- 不重命名、规范化或替换接口字段，除非后端契约或用户明确要求。
- 对缺失接口、缺失配置或权限不足场景给出显式错误或待确认说明。
- 补充必要的验证步骤或测试用例。

## 需要保留的现有逻辑

- 保留当前接口字段、请求路径、响应判断和错误提示策略，除非需求明确要求调整。
- 保留无关页面、模块、配置和构建脚本。

## 禁止事项

- 不执行危险命令。
- 不提交或推送被分析项目代码。
- 不读取或输出密钥、Token、密码等敏感信息。
- 不编造不存在的接口、字段、文件路径或业务规则。

## 错误处理要求

用户触发的接口动作失败时，应展示后端返回消息；静态分析无法确认的信息必须写入待确认问题。

## 配置与环境要求

{_list_or_unknown(context.build_scripts + context.test_scripts)}

补充材料摘要：

{docs_summary}

## 数据与接口影响

当前未确认具体数据表、接口字段或持久化变更。开发前需要从真实代码入口和接口契约中确认。

## 前端影响

如需求涉及页面展示、交互、按钮、弹窗、导航或状态反馈，需要验证完整事件链和用户可见结果。

## 后端影响

如需求涉及接口、权限、配置、任务或数据模型，需要确认控制器、服务、模型和数据库影响范围。

## 验收标准

- 能从真实入口定位到需求相关调用链。
- 实现结果满足测试输入描述的正常流程。
- 异常流程有明确提示，不静默失败。
- 不影响无关模块和现有接口契约。
- 输出或交付说明包含构建、测试和人工验证结果。

## 回归范围

- 与候选入口、候选文件和相邻业务流程相关的页面或接口。
- 构建脚本和测试脚本覆盖到的基础质量检查。

## 待确认问题

- 测试输入中未明确的平台、页面、接口、字段和验收细节。
- 外部文档中无法访问或无法静态确认的配置项。
- 是否需要创建远程 Issue、指定负责人、里程碑或标签。

## 风险点

- 静态扫描只能提供候选上下文，不能替代真实运行时验证。
- 文档链接可能受网络、权限或格式影响而无法完整提炼。
- 多平台项目需要避免把某个平台的实现误套到其他平台。

## Codex CLI Prompt

请在目标项目 `{context.root}` 中按只读优先方式完成以下开发任务：

测试输入：{qa_input.strip()}

已知项目上下文：

{context.to_markdown()}

要求：
- 先识别真实运行平台、入口文件、调用链和影响范围。
- 不修改无关文件，不读取或输出敏感信息。
- 不编造接口、字段、业务规则或文件路径。
- 对不确定信息写入待确认问题。
- 实现后验证事件绑定、请求触发、错误提示、构建或测试结果。
- 最终说明改动文件、验证结果、风险和仍需人工确认的内容。
"""


def _list_or_unknown(items: list[str]) -> str:
    if not items:
        return "- 暂未从轻量扫描中确认。"
    return "\n".join(f"- `{item}`" if not item.startswith("`") else f"- {item}" for item in items)


def _summarize_docs(extra_docs: str | None) -> str:
    if not extra_docs:
        return "- 未提供补充文档或文档链接。"
    trimmed = extra_docs[:2000].strip()
    return f"```text\n{trimmed}\n```"
